help_disk() {
  cat <<'EOF'
Arch Linux をインストールするディスクです。NVMe は通常ノート PC の高速な SSD、
sda/sdb は SATA ドライブや USB メモリです。起動に使った USB メモリは選ばないで
ください。
EOF
}

help_fs() {
  cat <<'EOF'
ファイルシステムは、ディスク上でファイルをどう管理するかを決めます。
• btrfs はスナップショットが作れます。更新で何かが壊れたときに戻れる、システム
  の「写真」です。ファイルを圧縮するので容量も節約できます。デスクトップや
  ノート PC には最良の選択です。
• ext4 は定番で、シンプルで実績があります。スナップショットも圧縮もありません。
• xfs は巨大なファイル（動画、データベース）に非常に強いですが、縮小できません。
EOF
}

help_snapshots() {
  cat <<'EOF'
スナップショットは自動の復元ポイントです。Reimu は pacman の更新のたびに一つ
作成し、数時間・数日分の履歴を保持します。何かが壊れても数秒で戻せます。GRUB
なら、スナップショットから直接起動することもできます。ファイルが変わらない
限り、容量はほとんど消費しません。
EOF
