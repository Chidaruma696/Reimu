help_sanae() {
  cat <<'EOF'
No Windows você instala programas de uma loja; no Arch você digita comandos do
pacman e procura nomes de pacotes. O Sanae é essa loja, para o terminal: mostra
os programas pelo que são (Internet, Jogos, Escritório, Desenvolvimento…) com o
nome de verdade e uma linha de descrição, diz quantos usuários do Arch têm cada
um e instala com uma tecla. Procura nos repositórios oficiais e no AUR (o
repositório da comunidade com milhares de programas a mais) ao mesmo tempo,
mantém o sistema atualizado avisando quando o Arch publica uma notícia que
precisa ser lida antes de atualizar, e limpa pacotes que sobraram.
Também tem "receitas": instalações de uma tecla que instalam um programa E o
deixam funcionando, coisa que gerenciadores de pacotes comuns nunca fazem.
Exemplos: Docker com o serviço rodando e seu usuário com acesso, máquinas
virtuais QEMU prontas para criar uma VM, digitação em japonês, fontes extras,
temas de área de trabalho.
Do mesmo autor do Reimu. É um software novo. Não substitui o pacman: roda o
pacman por você. Um único arquivo em /usr/local/bin/sanae; para remover:
sudo rm /usr/local/bin/sanae
EOF
}

