help_disk() {
  cat <<'EOF'
O disco onde o Arch Linux vai ficar. Os NVMe costumam ser o SSD rápido dos
notebooks; sda/sdb são discos SATA ou pendrives. Não escolha o pendrive de onde
você iniciou.
EOF
}

help_fs() {
  cat <<'EOF'
O sistema de arquivos é a forma como os arquivos ficam organizados no disco.
• btrfs sabe fazer snapshots: uma foto do sistema para a qual você volta se uma
  atualização quebrar algo. Também comprime arquivos, então você ganha espaço.
  A melhor escolha para desktop ou notebook.
• ext4 é o clássico, simples e comprovado. Sem snapshots nem compressão.
• xfs é muito rápido com arquivos enormes (vídeo, bancos de dados), mas não dá
  para encolher.
EOF
}

help_snapshots() {
  cat <<'EOF'
Snapshots são pontos de restauração automáticos. O Reimu tira um antes de cada
atualização do pacman e guarda algumas horas e dias de histórico. Se algo
quebrar, você volta em segundos. Com o GRUB dá até para iniciar direto num
snapshot. Custa quase nada enquanto seus arquivos ficam iguais.
EOF
}

help_kernels() {
  cat <<'EOF'
O kernel é o núcleo do Linux. "linux" é o normal. "linux-lts" é mais velho mas
tem suporte por mais tempo: uma segunda opção segura se o mais novo tiver
problemas com seu hardware. "zen" é ajustado para resposta rápida no desktop;
"hardened" troca um pouco de velocidade por segurança. Dá para instalar vários
e escolher na inicialização.
EOF
}

