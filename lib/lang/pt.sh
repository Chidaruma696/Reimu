help_swap() {
  local gib; gib="$(help_ram_gib)"
  cat <<EOF
Swap é memória reserva no disco, usada quando a RAM acaba. Sua máquina tem
${gib} GiB de RAM.
• zram comprime memória na própria RAM: rápido, sem espaço em disco, ideal para
  a maioria. Hibernar (suspender para o disco) não dá só com zram.
• Uma partição swap é necessária se quiser hibernar: pelo menos o tamanho da
  sua RAM (${gib} GiB).
• Um arquivo de swap é como uma partição, mas mais fácil de aumentar depois.
• Nenhum: tudo bem com bastante RAM, arriscado abaixo de 8 GiB.
EOF
}

