help_swap() {
  local gib; gib="$(help_ram_gib)"
  cat <<EOF
Swap ist Reservespeicher auf dem Datenträger, genutzt, wenn der RAM ausgeht.
Dein Rechner hat ${gib} GiB RAM.
• zram komprimiert Speicher im RAM selbst: schnell, kein Platz auf dem
  Datenträger, ideal für die meisten. Ruhezustand (auf Datenträger) geht mit
  zram allein nicht.
• Eine Swap-Partition ist nötig, wenn du den Ruhezustand willst: mindestens so
  groß wie dein RAM (${gib} GiB).
• Eine Swap-Datei ist wie eine Partition, aber später leichter zu vergrößern.
• Keiner: mit viel RAM in Ordnung, unter 8 GiB riskant.
EOF
}

