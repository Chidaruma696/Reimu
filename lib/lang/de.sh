help_disk_mode() {
  cat <<'EOF'
Automatisch löscht den ganzen Datenträger und legt die Partitionen für dich an.
Das ist richtig für einen Rechner, auf dem nur Arch Linux laufen wird.
Manuell lässt dich andere Systeme oder Partitionen behalten: du erstellst die
Partitionen mit cfdisk und sagst Reimu dann, welche welche ist.
EOF
}

help_disk() {
  cat <<'EOF'
Der Datenträger, auf dem Arch Linux landet. NVMe-Laufwerke sind meist die
schnelle SSD in Laptops; sda/sdb sind SATA-Laufwerke oder USB-Sticks. Nimm nicht
den USB-Stick, von dem du gestartet hast.
EOF
}

help_fs() {
  cat <<'EOF'
Das Dateisystem legt fest, wie Dateien auf dem Datenträger organisiert sind.
• btrfs kann Snapshots machen: ein Abbild des Systems, zu dem du zurückkehren
  kannst, wenn ein Update etwas kaputt macht. Es komprimiert auch Dateien, du
  gewinnst also Platz. Die beste Wahl für Desktop oder Laptop.
• ext4 ist der Klassiker, einfach und bewährt. Keine Snapshots, keine Kompression.
• xfs ist sehr schnell bei riesigen Dateien (Video, Datenbanken), lässt sich aber
  nicht verkleinern.
EOF
}

help_snapshots() {
  cat <<'EOF'
Snapshots sind automatische Wiederherstellungspunkte. Reimu erstellt vor jedem
pacman-Update einen und bewahrt ein paar Stunden und Tage Verlauf auf. Geht etwas
kaputt, bist du in Sekunden zurück. Mit GRUB kannst du sogar direkt in einen
Snapshot starten. Es kostet fast nichts, solange deine Dateien gleich bleiben.
EOF
}

help_kernels() {
  cat <<'EOF'
Der Kernel ist der Kern von Linux. "linux" ist der normale. "linux-lts" ist
älter, wird aber länger unterstützt: eine sichere zweite Wahl, falls der neueste
Probleme mit deiner Hardware hat. "zen" ist auf Reaktionsschnelligkeit am
Desktop abgestimmt; "hardened" tauscht etwas Tempo gegen Sicherheit. Du kannst
mehrere installieren und beim Start einen wählen.
EOF
}

