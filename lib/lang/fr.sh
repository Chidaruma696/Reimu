help_sanae() {
  cat <<'EOF'
Sous Windows on installe des programmes depuis une boutique ; sous Arch on tape
des commandes pacman et on cherche des noms de paquets. Sanae est cette
boutique, pour le terminal : elle montre les programmes selon ce qu'ils sont
(Internet, Jeux, Bureautique, Développement…) avec leur vrai nom et une ligne de
description, vous dit combien d'utilisateurs d'Arch ont chacun, et les installe
d'une touche. Elle cherche à la fois dans les dépôts officiels et dans l'AUR (le
dépôt communautaire avec des milliers de programmes de plus), garde votre
système à jour en vous prévenant quand Arch publie une nouvelle à lire avant de
mettre à jour, et sait nettoyer les paquets restants.
Elle a aussi des « recettes » : des installations d'une touche qui installent un
programme ET le laissent fonctionnel, ce que les gestionnaires de paquets
ordinaires ne font jamais. Exemples : Docker avec le service lancé et votre
utilisateur autorisé, des machines virtuelles QEMU prêtes à créer une VM, la
saisie en japonais, des polices supplémentaires, des thèmes de bureau.
Par le même auteur que Reimu. C'est un logiciel jeune. Elle ne remplace pas
pacman : elle exécute pacman pour vous. Un seul fichier dans
/usr/local/bin/sanae ; à retirer avec : sudo rm /usr/local/bin/sanae
EOF
}

