help_swap() {
  local gib; gib="$(help_ram_gib)"
  cat <<EOF
Le swap est de la mémoire de réserve sur le disque, utilisée quand la RAM
manque. Votre machine a ${gib} Gio de RAM.
• zram compresse la mémoire dans la RAM elle-même : rapide, sans espace disque,
  idéal pour la plupart des gens. L'hibernation (mise en veille sur disque) n'est
  pas possible avec zram seul.
• Une partition swap est indispensable pour hiberner : au moins la taille de
  votre RAM (${gib} Gio).
• Un fichier swap est comme une partition, mais plus facile à redimensionner.
• Aucun : très bien avec beaucoup de RAM, risqué sous 8 Gio.
EOF
}

