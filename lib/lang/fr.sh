help_disk_mode() {
  cat <<'EOF'
Automatique efface tout le disque et crée les partitions pour vous. C'est le bon
choix pour une machine qui ne fera tourner qu'Arch Linux.
Manuel vous laisse garder d'autres systèmes ou partitions : vous créez les
partitions avec cfdisk, puis vous dites à Reimu laquelle est laquelle.
EOF
}

help_disk() {
  cat <<'EOF'
Le disque qui accueillera Arch Linux. Les NVMe sont généralement le SSD rapide
des portables ; sda/sdb sont des disques SATA ou des clés USB. Ne choisissez pas
la clé USB depuis laquelle vous avez démarré.
EOF
}

help_fs() {
  cat <<'EOF'
Le système de fichiers est la façon dont les fichiers sont organisés sur le disque.
• btrfs sait faire des instantanés : une photo du système à laquelle revenir si
  une mise à jour casse quelque chose. Il compresse aussi les fichiers, donc vous
  gagnez de la place. Le meilleur choix pour un ordinateur de bureau ou portable.
• ext4 est le classique, simple et éprouvé. Ni instantanés ni compression.
• xfs est très rapide avec les gros fichiers (vidéo, bases de données) mais ne
  peut pas être réduit.
EOF
}

help_snapshots() {
  cat <<'EOF'
Les instantanés sont des points de restauration automatiques. Reimu en prend un
avant chaque mise à jour pacman et garde quelques heures et jours d'historique.
Si quelque chose casse, vous revenez en arrière en quelques secondes. Avec GRUB,
vous pouvez même démarrer directement sur un instantané. Ça ne coûte presque
rien tant que vos fichiers ne changent pas.
EOF
}

help_kernels() {
  cat <<'EOF'
Le noyau est le cœur de Linux. « linux » est le normal. « linux-lts » est plus
ancien mais soutenu plus longtemps : une seconde option sûre si le plus récent
pose problème avec votre matériel. « zen » est réglé pour la réactivité sur le
bureau ; « hardened » échange un peu de vitesse contre de la sécurité. Vous
pouvez en installer plusieurs et en choisir un au démarrage.
EOF
}

help_user() {
