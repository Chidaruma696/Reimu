help_repos() {
  cat <<'EOF'
I repository sono le fonti da cui pacman installa. Quelli di Arch sono sempre
attivi.
• multilib: librerie a 32 bit ufficiali; Steam, Wine e molti giochi ne hanno
  bisogno.
• Chaotic-AUR: un repository della comunità con migliaia di programmi AUR già
  compilati (browser, editor, giochi, font…) che installi in pochi secondi
  invece di compilarli. Molto usato; mantenuto da membri della comunità Arch.
ATTENZIONE: tutto ciò che sta fuori dai repository ufficiali (Chaotic-AUR,
repository personalizzati, l'AUR stesso) non è revisionato da Arch Linux. Un
pacchetto da lì può rompere un aggiornamento o contenere qualsiasi cosa. Attiva
solo ciò che capisci. Altre fonti (Liquorix, BlackArch, ALHP, Flatpak, Snap) si
possono attivare dopo dalle impostazioni di Sanae, con lo stesso avviso.
EOF
}

