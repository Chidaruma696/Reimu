help_sanae() {
  cat <<'EOF'
Su Windows installi i programmi da un negozio; su Arch scrivi comandi pacman e
cerchi nomi di pacchetti. Sanae è quel negozio, per il terminale: mostra i
programmi per quello che sono (Internet, Giochi, Ufficio, Sviluppo…) con il
loro vero nome e una riga di descrizione, ti dice quanti utenti Arch hanno
ciascuno e li installa con un tasto. Cerca nei repository ufficiali e nell'AUR
(il repository della comunità con migliaia di programmi in più) insieme, tiene
aggiornato il sistema avvisandoti quando Arch pubblica una notizia da leggere
prima di aggiornare, e ripulisce i pacchetti rimasti.
Ha anche le "ricette": configurazioni con un tasto che installano un programma
E lo lasciano funzionante, cosa che i gestori di pacchetti normali non fanno
mai. Esempi: Docker con il servizio avviato e il tuo utente autorizzato,
macchine virtuali QEMU pronte per creare una VM, scrittura in giapponese, font
aggiuntivi, temi per il desktop.
Dello stesso autore di Reimu. È un software giovane. Non sostituisce pacman: lo
esegue per te. Un solo file in /usr/local/bin/sanae; per toglierlo:
sudo rm /usr/local/bin/sanae
EOF
}

