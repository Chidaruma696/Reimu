help_fs() {
  cat <<'EOF'
Il filesystem è il modo in cui i file sono organizzati sul disco.
• btrfs sa fare snapshot: una fotografia del sistema a cui tornare se un
  aggiornamento rompe qualcosa. Comprime anche i file, quindi guadagni spazio.
  La scelta migliore per desktop o portatile.
• ext4 è il classico, semplice e collaudato. Niente snapshot né compressione.
• xfs è velocissimo con i file enormi (video, database) ma non si può ridurre.
EOF
}

help_snapshots() {
  cat <<'EOF'
Gli snapshot sono punti di ripristino automatici. Reimu ne fa uno prima di ogni
aggiornamento di pacman e conserva qualche ora e giorno di storico. Se qualcosa
si rompe, torni indietro in pochi secondi. Con GRUB puoi persino avviare
direttamente uno snapshot. Non costa quasi nulla finché i tuoi file restano
uguali.
EOF
}

help_kernels() {
  cat <<'EOF'
Il kernel è il cuore di Linux. "linux" è quello normale. "linux-lts" è più
