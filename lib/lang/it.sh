help_swap() {
  local gib; gib="$(help_ram_gib)"
  cat <<EOF
Lo swap è memoria di riserva su disco, usata quando la RAM finisce. Il tuo
computer ha ${gib} GiB di RAM.
• zram comprime la memoria nella RAM stessa: veloce, niente spazio su disco,
  ideale per la maggior parte delle persone. L'ibernazione (sospensione su
  disco) non è possibile solo con zram.
• Una partizione swap serve se vuoi ibernare: almeno quanto la tua RAM
  (${gib} GiB).
• Un file di swap è come una partizione, ma più facile da ingrandire dopo.
• Nessuno: va bene con molta RAM, rischioso sotto gli 8 GiB.
EOF
}

help_bootloader() {
  local note=""
  if [[ "$DETECT_FIRMWARE" == bios ]]; then
    note=$'\nQuesto computer si è avviato in modalità BIOS (legacy), quindi systemd-boot non si\npuò offrire. In VirtualBox attiva "Enable EFI" in Sistema; in QEMU usa OVMF; su un\nPC vero cerca la modalità UEFI nelle impostazioni del firmware.'
  fi
  cat <<EOF
Il bootloader è il piccolo programma che avvia Linux quando accendi il computer.
• systemd-boot è semplice e veloce, con un menu essenziale. Solo UEFI.
• GRUB mostra un menu completo, può avviare altri sistemi (Windows) e gli
  snapshot btrfs. Funziona su UEFI e sui vecchi computer BIOS.
• Limine è moderno e minuscolo, con un menu pulito, e funziona su UEFI e
  BIOS.${note}
EOF
}

